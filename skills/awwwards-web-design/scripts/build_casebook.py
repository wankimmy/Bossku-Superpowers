#!/usr/bin/env python3
"""Render references/casebook.md from the audited teardown JSONs (no model in the loop).

  python3 build_casebook.py --teardowns data/teardowns --sample data/sample.json --out references/casebook.md
"""
import argparse
import json
from datetime import date
from pathlib import Path

BUCKET_TITLES = {
    "site-of-the-year": "Sites of the Year",
    "site-of-the-month": "Sites of the Month",
    "3d-webgl": "3D and WebGL",
    "typography": "Typography-led",
    "e-commerce": "E-commerce and product",
    "portfolio-agency": "Portfolios and agencies",
    "motion-transitions": "Motion and transitions",
    "category-mix": "Architecture, culture, experimental",
    "recent-sotd": "Recent Sites of the Day",
}


def clip(text, n):
    text = " ".join(str(text or "").split())
    return text if len(text) <= n else text[: n - 1].rsplit(" ", 1)[0] + "…"


def fams(t):
    out = []
    for f in (t.get("typography") or {}).get("families") or []:
        if isinstance(f, dict) and f.get("name"):
            out.append(f"{f['name']} ({f.get('role', '?')})")
    return ", ".join(out[:4]) or "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--teardowns", type=Path, required=True)
    ap.add_argument("--sample", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    sample = json.loads(a.sample.read_text())
    lines = ["# Casebook: 51 Awwwards winners, torn down", "", f"Last updated: {date.today().isoformat()}", "",
             "Generated by `scripts/build_casebook.py` from the audited teardowns in `data/teardowns/`",
             "(one JSON per site, built from scroll screenshots, jury element frames, probe measurements and bundle greps).",
             "Open the JSON for the full evidence. Take the design language, never the content.", ""]
    for bucket, title in BUCKET_TITLES.items():
        sites = [s for s in sample if s["bucket"] == bucket]
        if not sites:
            continue
        lines += [f"## {title}", ""]
        for s in sites:
            f = a.teardowns / f"{s['slug']}.json"
            if not f.exists():
                lines += [f"### {s['title']}", "", "_teardown missing_", ""]
                continue
            t = json.loads(f.read_text())
            color = t.get("color") or {}
            three = t.get("three_d") or {}
            stack = t.get("tech_stack") or {}
            libs = ", ".join((stack.get("libraries") or [])[:6])
            lines += [
                f"### {s['title']}",
                f"{s.get('award') or ''} · jury {s.get('score')} · [live]({s['live_url']}) · "
                f"[awwwards](https://www.awwwards.com/sites/{s['slug']}) · `data/teardowns/{s['slug']}.json`",
                "",
                f"**Signature.** {clip(t.get('signature'), 320)}",
                "",
                f"- **Stack:** {clip(stack.get('framework'), 60) or 'n/a'}; {libs or 'n/a'}"
                + (f"; 3D: {clip(three.get('stack'), 60)}, {clip(three.get('role'), 90)}" if three.get("present") else ""),
                f"- **Type:** {clip(fams(t), 200)}" + (f"; display {dsp}px" if (dsp := (t.get('typography') or {}).get('display_size_px')) else ""),
                f"- **Color:** {clip(color.get('mode'), 40)}; base {clip(color.get('base'), 50)}; ink {clip(color.get('ink'), 40)}"
                + (f"; accents {clip(', '.join(map(str, color.get('accents') or [])), 90)}" if color.get("accents") else ""),
                f"- **Motion:** {clip((t.get('motion') or {}).get('choreography_notes') or (t.get('motion') or {}).get('intro_sequence'), 260)}",
                "",
                "Steal:",
            ]
            for st in (t.get("steal_this") or [])[:4]:
                if isinstance(st, dict):
                    lines.append(f"- *{clip(st.get('technique'), 90)}*: {clip(st.get('how_to_build'), 300)}")
            risks = [r for r in (t.get("slop_risks") or []) if r][:2]
            if risks:
                lines += ["", "Watch out: " + " / ".join(clip(r, 200) for r in risks)]
            lines.append("")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {a.out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
